"""Generate the CLI banner's art from the CLI logo's SVG.

Draws ``docs/assets/boilerplate-cli-logo.svg`` in braille dots, 11 rows tall at
every width from 22 to 29 columns, sets the name in FIGlet's ``standard`` font,
and writes ``src/boilerplate/cli/display/banner_art.py``. The rules the art
follows are in docs/design/05-cli-reference.md §Banner.

Each dot is 8 by 8 samples of the SVG, and lights when enough of them fall
inside its shape: a brace's filled outline, with its curves flattened into a
polygon, or within half the stroke width of a bar's or the prompt's segments,
which draws their round caps and joins. Each shape maps the SVG's y to dot rows
through its own vertical fit, so the bars land on 2-row bands 4 rows apart, the
chevron's tip on a row boundary so its arms mirror, the underscore on the bottom
3 rows, and the braces' feet on the cell row above the underscore's. The prompt
is painted last, over the braces and bars, on the rows its own fit gives it. A
bar lights a whole column at a time, both its rows or neither, so a bar's end
that shows past the prompt keeps the bar's height.

Usage:
    uv run python scripts/render_cli_banner.py
"""

import argparse
import json
import re
import xml.etree.ElementTree as ET
from collections.abc import Callable, Mapping, Sequence
from itertools import pairwise
from pathlib import Path
from typing import Final, NamedTuple

import numpy as np
import pyfiglet
from numpy.typing import NDArray

_REPO_ROOT: Final = Path(__file__).resolve().parent.parent
_SOURCE: Final = _REPO_ROOT / "docs" / "assets" / "boilerplate-cli-logo.svg"
_TARGET: Final = (
    _REPO_ROOT / "src" / "boilerplate" / "cli" / "display" / "banner_art.py"
)

ROWS: Final = 11
WIDTHS: Final = range(22, 30)
_DOT_ROWS: Final = ROWS * 4
_SAMPLES: Final = 8  # samples per dot along each axis
_VIEWBOX: Final = 128.0  # the SVG's width and height
_PLAIN: Final = _VIEWBOX / _DOT_ROWS  # SVG units per dot row, unfitted

# The share of a dot's samples its shape must cover to light it. The braces'
# share sits a little under half, so the dots on the edges of their curves
# stay lit; at half, a few of them drop out at every width.
_BRACE_COVERAGE: Final = 0.45
_STROKE_COVERAGE: Final = 0.5

# Vertical fits, in dot rows. The bars are 2 rows tall, 4 apart, the first
# centered on row boundary 6. The chevron's tip sits on boundary 31. The
# underscore takes the bottom 3 rows. The braces follow the plain stretch down
# to y=100, then close up so their feet end on boundary 40, the top of the
# underscore's cell row, and never share a cell with it.
_BAR_ROWS: Final = 2
_BAR_PITCH: Final = 4.0
_FIRST_BAR_CENTER: Final = 6.0
_CHEVRON_AXIS: Final = 31.0
_UNDERSCORE_ROWS: Final = 3.0
_BRACE_FIT_FROM: Final = 100.0
_BRACE_FEET: Final = 40.0

_BLUE_FILL: Final = "#40B4E5"
# The logo's parts, counted in the SVG: eight bars, and a prompt drawn as a
# 3-point chevron (two ends and the tip) and a 2-point underscore.
_BARS: Final = 8
_CHEVRON_POINTS: Final = 3
_UNDERSCORE_POINTS: Final = 2
_PROMPT_STROKE: Final = "black"  # the SVG's prompt color; it is themed when shown
_EMPTY, _BLUE, _PROMPT = 0, 1, 2

# Each braille dot's (column, row) within its 2 by 4 cell, and its bit.
_BRAILLE_BITS: Final = (
    (0, 0, 0x01),
    (0, 1, 0x02),
    (0, 2, 0x04),
    (1, 0, 0x08),
    (1, 1, 0x10),
    (1, 2, 0x20),
    (0, 3, 0x40),
    (1, 3, 0x80),
)
_PATH_TOKEN: Final = re.compile(r"[A-Za-z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
_CURVE_STEPS: Final = 48  # straight segments per flattened Bezier curve

_MODULE_HEADER: Final = '''"""Braille logo and ASCII name for the CLI banner.

Generated by scripts/render_cli_banner.py from
docs/assets/boilerplate-cli-logo.svg; regenerate it rather than edit it. The
banner's contract is docs/design/05-cli-reference.md §Banner.

Attributes:
    NAME: The name ``boilerplate`` in FIGlet's ``standard`` font, one string
        per row.
    LOGOS: The logo's rows at each width in columns.
    LOGO_COLORS: One mask per logo row, at each width: ``b`` marks a brand
        blue cell, ``p`` a prompt cell, and a space an empty one.
"""

from collections.abc import Mapping
from typing import Final
'''

type Point = tuple[float, float]
type Floats = NDArray[np.float64]
type Warp = Callable[[Floats], Floats]


class LogoShapes(NamedTuple):
    """The logo's shapes, in SVG units.

    Attributes:
        braces: The two braces' outlines, as closed polygons.
        bars: The eight bars' center lines, top to bottom.
        bar_half_width: Half a bar's stroke width.
        chevron: The chevron's center line: its two ends and its tip between.
        underscore: The underscore's center line.
        prompt_half_width: Half the prompt's stroke width.
    """

    braces: list[Floats]
    bars: list[tuple[Point, Point]]
    bar_half_width: float
    chevron: tuple[Point, ...]
    underscore: tuple[Point, ...]
    prompt_half_width: float


def subpaths(d: str) -> list[list[Point]]:
    """Return an SVG path's subpaths as point lists, curves flattened.

    Reads the absolute commands the logo uses: M, L, H, V, C and Z, with
    repeated coordinates continuing the last command. Drawing after a Z goes
    on from the closed subpath's first point, as SVG specifies.

    Args:
        d: The path's ``d`` attribute.

    Returns:
        One list of points per subpath. Z adds no point, so a subpath that
        draws back to its start ends on its first point again.

    Raises:
        ValueError: The path does not start with M, uses a command this
            reader does not handle, or gives a command too few numbers.
    """
    tokens = _PATH_TOKEN.findall(d)
    if tokens[:1] not in ([], ["M"]):
        raise ValueError("An SVG path must start with M.")
    paths: list[list[Point]] = []
    points: list[Point] = []
    current: Point = (0.0, 0.0)
    command = ""
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token.isalpha():
            if token not in "MLHVCZ":
                raise ValueError(f"Unsupported SVG path command {token!r}.")
            command = token
            index += 1
            if command == "Z" and points:
                paths.append(points)
                current, points = points[0], []
            continue
        arity = _ARITY.get(command, 0)
        values = tokens[index : index + arity]
        if not arity or len(values) < arity or any(v.isalpha() for v in values):
            raise ValueError(
                f"SVG path command {command!r} takes {arity} numbers at a time."
            )
        numbers = [float(value) for value in values]
        index += arity
        if command == "M":
            if points:
                paths.append(points)
            current = (numbers[0], numbers[1])
            points = [current]
            command = "L"  # coordinates after a move draw lines
            continue
        if not points:
            points = [current]  # drawing on after a Z
        if command == "C":
            points += _flatten(current, numbers)
            current = (numbers[4], numbers[5])
        else:
            current = _line_end(command, current, numbers)
            points.append(current)
    if points:
        paths.append(points)
    return paths


_ARITY: Final = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6}


def _line_end(command: str, current: Point, numbers: Sequence[float]) -> Point:
    """Return where an L, H or V command drawn from ``current`` ends."""
    if command == "H":
        return (numbers[0], current[1])
    if command == "V":
        return (current[0], numbers[0])
    return (numbers[0], numbers[1])


def _flatten(start: Point, values: Sequence[float]) -> list[Point]:
    """Return a cubic Bezier curve's points after ``start``, in equal steps."""
    p0 = np.array(start)
    p1, p2, p3 = (np.array(values[i : i + 2]) for i in (0, 2, 4))
    points: list[Point] = []
    for s in np.linspace(0, 1, _CURVE_STEPS + 1)[1:]:
        q = (
            (1 - s) ** 3 * p0
            + 3 * (1 - s) ** 2 * s * p1
            + 3 * (1 - s) * s**2 * p2
            + s**3 * p3
        )
        points.append((float(q[0]), float(q[1])))
    return points


def logo_shapes(svg: str) -> LogoShapes:
    """Read the braces, bars and prompt out of the logo's SVG.

    Args:
        svg: The SVG document's text.

    Returns:
        The logo's shapes.

    Raises:
        ValueError: The SVG no longer holds eight evenly spaced horizontal
            bars, one chevron and one underscore.
    """
    braces: list[Floats] = []
    bars: list[tuple[Point, Point]] = []
    prompt: list[list[Point]] = []
    bar_half_width = prompt_half_width = 0.0
    # The SVG is this repository's own asset, not outside input.
    for element in ET.fromstring(svg).iter():
        d = element.get("d")
        if d is None:
            continue
        if element.get("fill") == _BLUE_FILL:
            braces += [np.array(points) for points in subpaths(d)]
        elif element.get("stroke") == _BLUE_FILL:
            bar_half_width = float(element.get("stroke-width", "0")) / 2
            bars += [(points[0], points[-1]) for points in subpaths(d)]
        elif element.get("stroke") == _PROMPT_STROKE:
            prompt_half_width = float(element.get("stroke-width", "0")) / 2
            prompt += subpaths(d)
    bars.sort(key=lambda bar: bar[0][1])
    _check_bars(bars)
    chevrons = [tuple(points) for points in prompt if len(points) == _CHEVRON_POINTS]
    underscores = [
        tuple(points) for points in prompt if len(points) == _UNDERSCORE_POINTS
    ]
    if len(chevrons) != 1 or len(underscores) != 1:
        raise ValueError(
            "The logo's prompt is no longer one chevron and one underscore."
        )
    return LogoShapes(
        braces, bars, bar_half_width, chevrons[0], underscores[0], prompt_half_width
    )


def _check_bars(bars: Sequence[tuple[Point, Point]]) -> None:
    """Fail unless ``bars`` are eight horizontal lines at one even spacing."""
    ys = [start[1] for start, end in bars if start[1] == end[1]]
    gaps = {round(b - a, 6) for a, b in pairwise(ys)}
    if len(bars) != _BARS or len(ys) != _BARS or len(gaps) != 1:
        raise ValueError("The logo no longer has eight evenly spaced horizontal bars.")


def _warps(shapes: LogoShapes) -> dict[str, Warp]:
    """Return each shape's vertical fit, from dot rows to SVG y."""
    bar_ys = [start[1] for start, _ in shapes.bars]
    slope = _BAR_PITCH / (bar_ys[1] - bar_ys[0])  # dot rows per SVG unit
    bars_middle = sum(bar_ys) / len(bar_ys)
    rows_middle = _FIRST_BAR_CENTER + _BAR_PITCH * (len(bar_ys) - 1) / 2
    tip_y = shapes.chevron[1][1]
    underscore_y = shapes.underscore[0][1]
    underscore_slope = _UNDERSCORE_ROWS / (2 * shapes.prompt_half_width)
    underscore_middle = _DOT_ROWS - _UNDERSCORE_ROWS / 2
    feet_y = max(float(polygon[:, 1].max()) for polygon in shapes.braces)
    fit_from = _BRACE_FIT_FROM / _PLAIN

    def braces(u: Floats) -> Floats:
        squeezed = _BRACE_FIT_FROM + (u - fit_from) * (feet_y - _BRACE_FIT_FROM) / (
            _BRACE_FEET - fit_from
        )
        return np.where(u <= fit_from, u * _PLAIN, squeezed)

    return {
        "braces": braces,
        "bars": lambda u: bars_middle + (u - rows_middle) / slope,
        "chevron": lambda u: tip_y + (u - _CHEVRON_AXIS) / slope,
        "underscore": lambda u: (
            underscore_y + (u - underscore_middle) / underscore_slope
        ),
    }


def _inside(x: Floats, y: Floats, polygon: Floats) -> NDArray[np.bool_]:
    """Return which points of a grid fall inside ``polygon``, by the even-odd rule.

    The grid has one column per value of ``x`` and one row per value of ``y``.
    Each edge is tested only against the rows it crosses.
    """
    inside = np.zeros((y.size, x.size), bool)
    x0, y0 = polygon[-1]
    for x1, y1 in polygon:
        if y0 != y1:
            rows = np.flatnonzero((y0 > y) != (y1 > y))
            meet = x0 + (y[rows] - y0) * (x1 - x0) / (y1 - y0)
            inside[rows] ^= x[None, :] < meet[:, None]
        x0, y0 = x1, y1
    return inside


def _near(
    x: Floats, y: Floats, line: Sequence[Point], half: float
) -> NDArray[np.bool_]:
    """Return which points lie within ``half`` of a polyline's segments."""
    near = np.zeros(x.shape, bool)
    for (ax, ay), (bx, by) in pairwise(line):
        dx, dy = bx - ax, by - ay
        t = np.clip(((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy), 0, 1)
        near |= np.hypot(x - (ax + t * dx), y - (ay + t * dy)) <= half
    return near


def _coverage(shapes: LogoShapes, width: int) -> dict[str, Floats]:
    """Return each shape's share of every dot's samples, at ``width`` columns.

    The braces and bars count only the samples the prompt leaves visible, as
    the prompt is painted over them. Each shape has its own vertical fit, so
    the prompt hides the samples where the art draws it, not where the SVG
    does.
    """
    columns = 2 * width * _SAMPLES
    x = (np.arange(columns) + 0.5) / _SAMPLES * _VIEWBOX / (2 * width)
    u = (np.arange(_DOT_ROWS * _SAMPLES) + 0.5) / _SAMPLES
    warps = _warps(shapes)
    half = shapes.prompt_half_width

    def grid(warp: Warp) -> tuple[Floats, Floats]:
        sx, sy = np.broadcast_arrays(x[None, :], warp(u)[:, None])
        return sx, sy

    def per_dot(samples: NDArray[np.bool_]) -> Floats:
        return samples.reshape(_DOT_ROWS, _SAMPLES, 2 * width, _SAMPLES).mean(
            axis=(1, 3)
        )

    chevron = _near(*grid(warps["chevron"]), shapes.chevron, half)
    underscore = _near(*grid(warps["underscore"]), shapes.underscore, half)
    prompt = chevron | underscore
    braces = np.zeros(prompt.shape, bool)
    for polygon in shapes.braces:
        braces |= _inside(x, warps["braces"](u), polygon)
    sx, sy = grid(warps["bars"])
    bars = np.zeros(sx.shape, bool)
    for bar in shapes.bars:
        bars |= _near(sx, sy, bar, shapes.bar_half_width)
    return {
        "braces": per_dot(braces & ~prompt),
        "bars": per_dot(bars & ~prompt),
        "chevron": per_dot(chevron),
        "underscore": per_dot(underscore),
    }


def one_color_per_cell(grid: NDArray[np.int8]) -> NDArray[np.int8]:
    """Drop the blue dots of every character cell that holds a prompt dot.

    A cell prints in one color, and the prompt is painted over the bars.

    Args:
        grid: Dots as ``0`` (empty), ``1`` (blue) or ``2`` (prompt), one row
            per dot row.

    Returns:
        A copy of ``grid`` with those blue dots emptied.
    """
    resolved = grid.copy()
    for top in range(0, resolved.shape[0], 4):
        for left in range(0, resolved.shape[1], 2):
            cell = resolved[top : top + 4, left : left + 2]
            if (cell == _PROMPT).any():
                cell[cell == _BLUE] = _EMPTY
    return resolved


def _rows(grid: NDArray[np.int8]) -> list[tuple[str, str]]:
    """Return a dot grid as rows of braille characters and their masks."""
    rows: list[tuple[str, str]] = []
    for top in range(0, grid.shape[0], 4):
        chars: list[str] = []
        marks: list[str] = []
        for left in range(0, grid.shape[1], 2):
            bits, color = 0, _EMPTY
            for dx, dy, bit in _BRAILLE_BITS:
                dot = int(grid[top + dy, left + dx])
                if dot != _EMPTY:
                    bits, color = bits | bit, dot
            chars.append(chr(0x2800 + bits) if bits else " ")
            marks.append({_EMPTY: " ", _BLUE: "b", _PROMPT: "p"}[color])
        rows.append(("".join(chars), "".join(marks)))
    return rows


def render_logo(shapes: LogoShapes, width: int) -> list[tuple[str, str]]:
    """Draw the logo in braille, ``ROWS`` tall and ``width`` columns wide.

    Args:
        shapes: The logo's shapes.
        width: The logo's width in terminal columns.

    Returns:
        The logo's rows as ``(characters, mask)`` pairs.
    """
    coverage = _coverage(shapes, width)
    bar_tops = [
        round(_FIRST_BAR_CENTER + _BAR_PITCH * index - _BAR_ROWS / 2)
        for index in range(len(shapes.bars))
    ]
    blue = (coverage["braces"] >= _BRACE_COVERAGE) | light_bars(
        coverage["bars"], bar_tops
    )
    prompt = (coverage["chevron"] >= _STROKE_COVERAGE) | (
        coverage["underscore"] >= _STROKE_COVERAGE
    )
    grid = np.where(prompt, _PROMPT, np.where(blue, _BLUE, _EMPTY)).astype(np.int8)
    return _rows(one_color_per_cell(grid))


def light_bars(coverage: Floats, tops: Sequence[int]) -> NDArray[np.bool_]:
    """Return which dots the bars light, both of a bar's rows or neither.

    Where the prompt or a bar's round end covers only part of a column, the
    column lights when the bar covers at least half of its two rows' samples,
    so a bar's end that shows past the prompt keeps the bar's height instead
    of thinning to one dot.

    Args:
        coverage: The bars' visible share of every dot's samples, one row per
            dot row.
        tops: Each bar's top dot row.

    Returns:
        Which dots the bars light, in ``coverage``'s shape.
    """
    lit = np.zeros(coverage.shape, bool)
    for top in tops:
        band = coverage[top : top + _BAR_ROWS].mean(axis=0) >= _STROKE_COVERAGE
        lit[top : top + _BAR_ROWS] = band
    return lit


def module_source(
    name: Sequence[str], logos: Mapping[int, Sequence[tuple[str, str]]]
) -> str:
    """Return the source of the art module the CLI imports.

    Args:
        name: The name's rows.
        logos: The logo's rows at each width in columns, as
            ``(characters, mask)`` pairs.

    Returns:
        Python source in the layout ruff's formatter keeps.
    """
    lines = [_MODULE_HEADER, "NAME: Final[tuple[str, ...]] = ("]
    lines += [f"    {_literal(row)}," for row in name]
    lines.append(")")
    for variable, part in (("LOGOS", 0), ("LOGO_COLORS", 1)):
        lines += ["", f"{variable}: Final[Mapping[int, tuple[str, ...]]] = {{"]
        for columns, rows in logos.items():
            lines.append(f"    {columns}: (")
            lines += [f"        {_literal(row[part])}," for row in rows]
            lines.append("    ),")
        lines.append("}")
    return "\n".join(lines) + "\n"


def _literal(text: str) -> str:
    """Return a double-quoted Python string literal for ``text``."""
    return json.dumps(text, ensure_ascii=False)


def render_name() -> tuple[str, ...]:
    """Return the name ``boilerplate`` in FIGlet's ``standard`` font."""
    art = pyfiglet.figlet_format("boilerplate", font="standard")
    return tuple(row.rstrip() for row in art.splitlines() if row.strip())


def main(argv: Sequence[str] | None = None) -> int:
    """Render every logo width and the name, and write the art module.

    Args:
        argv: The command-line arguments, or None to read ``sys.argv``. The
            script takes none; ``--help`` prints this module's docstring.

    Returns:
        Process exit code: 0 once the module is written.
    """
    argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    ).parse_args(argv)
    shapes = logo_shapes(_SOURCE.read_text(encoding="utf-8"))
    logos = {columns: render_logo(shapes, columns) for columns in WIDTHS}
    _TARGET.write_text(
        module_source(render_name(), logos), encoding="utf-8", newline="\n"
    )
    target = _TARGET.relative_to(_REPO_ROOT).as_posix()
    print(f"Wrote {target}: the name and the logo at {len(logos)} widths.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
